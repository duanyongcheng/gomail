#!/usr/bin/env python3
"""Refresh the explicit command manifest."""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
implemented = set(re.findall(r'^  ([a-z_][a-z_0-9]*): implemented', (root / 'src/lib/platform/commands.ts').read_text(), re.M))
names = set()
for path in (root / 'src').rglob('*.ts*'):
    if 'platform' in path.parts or 'poc' in path.parts:
        continue
    names.update(re.findall(r'\binvoke(?:<[^;]*?>)?\(\s*["\']([^"\']+)', path.read_text()))
arrays = set('list_kanban_cards get_message_labels list_labels list_contacts search_contacts search_contact_suggestions list_email_templates list_rules list_snoozed list_trusted_senders list_threads take_pending_mailto_urls'.split())
nulls = set('get_contact_by_email ai_get_config get_translate_config load_auto_backup_config get_global_proxy get_account_proxy get_oauth_account_proxy get_xoauth2_status'.split())
objects = set('get_message_labels_batch list_kanban_context_notes'.split())
noops = set('set_notifications_enabled set_tray_menu_labels sync_titlebar_theme clear_notification_attention'.split())
strings = set('get_email_signature migrate_email_signature_if_absent'.split())
special = {
    'get_autostart_enabled': 'false',
    'is_trusted_sender': 'false',
    'get_notification_status': '{ enabled: false, attention_active: false, platform: "unknown", app_id: null }',
    'get_account_proxy_setting': '{ mode: "inherit", proxy: null }',
    'get_oauth_account_proxy_setting': '{ mode: "inherit", proxy: null }',
}

def milestone(name):
    if name == 'advanced_search':
        return 'M3'
    if any(w in name for w in ('proxy', 'imap', 'pop3', 'xoauth2', 'test_account', 'add_account')):
        return 'M2'
    if any(w in name for w in ('webdav', 'backup', 'translate', 'ai_')):
        return 'M5'
    if any(w in name for w in ('notification', 'autostart', 'tray', 'titlebar', 'mailto', 'external', 'default_mail', 'app_log')):
        return 'M4'
    if any(w in name for w in ('contact', 'kanban', 'snooze', 'rule', 'template', 'signature', 'background', 'message_label', 'trusted', 'labels', 'reorder', 'update_account')):
        return 'M3'
    return 'M1'

source = ['// Generated by scripts/generate_commands.py. Review status changes before refreshing.',
          'import { implementedCommands, pending, startup } from "./commands";',
          'export const commands = {', '  ...implementedCommands,']
for name in sorted(names):
    if name in implemented:
        continue
    target = milestone(name)
    value = None
    if name in arrays: value = '[]'
    elif name in nulls or name in noops: value = 'null'
    elif name in objects: value = '{}'
    elif name in strings: value = '\'\''
    elif name in special: value = special[name]
    if value is None:
        if name == 'set_xoauth2_refresh':
            source.append('  set_xoauth2_refresh: pending("set_xoauth2_refresh", "M2", "Raw refresh-token import is unsupported. Use Microsoft sign-in in account settings to verify the mailbox and authorize IMAP and SMTP separately."),')
        else:
            source.append(f'  {name}: pending("{name}", "{target}"),')
    else:
        source.append(f'  {name}: startup({value}, "{target}"),')
source.extend(['} as const;', 'export type CommandName = keyof typeof commands;', ''])
(root / 'src/lib/platform/manifest.ts').write_text('\n'.join(source))
print(f'{len(names)} commands, {len(implemented)} implemented; manifest refreshed')
