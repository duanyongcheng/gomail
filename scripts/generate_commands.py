#!/usr/bin/env python3
"""Refresh the explicit command manifest and parity documentation."""
import argparse
import re
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--manifest-only', action='store_true', help='Leave parent-owned parity documentation unchanged')
args = parser.parse_args()

root = Path(__file__).resolve().parents[1]
implemented = set(re.findall(r'^  ([a-z_][a-z_0-9]*): implemented', (root / 'src/lib/platform/commands.ts').read_text(), re.M))
m2_commands = {'add_account', 'test_account_connection', 'test_imap_connection', 'test_pop3_connection',
    'get_global_proxy', 'update_global_proxy', 'get_account_proxy', 'get_account_proxy_setting',
    'update_account_proxy', 'update_account_proxy_setting', 'get_oauth_account_proxy',
    'get_oauth_account_proxy_setting', 'update_oauth_account_proxy', 'update_oauth_account_proxy_setting',
    'get_imap_sync_folders', 'update_imap_sync_folders', 'get_xoauth2_status'}
m1_commands = {'start_sync', 'stop_sync', 'set_realtime_preference', 'trigger_sync',
    'archive_message', 'delete_message', 'restore_message', 'move_to_folder',
    'batch_archive', 'batch_delete', 'batch_mark_read', 'batch_star',
    'mark_account_all_read', 'mark_folder_all_read', 'empty_trash',
    'get_pending_mail_ops_summary', 'list_pending_mail_ops', 'dismiss_failed_pending_mail_ops', 'get_messages_batch',
    'get_attachment_path', 'download_attachment', 'save_draft', 'delete_draft',
    'stage_compose_attachment', 'cleanup_staged_compose_attachment', 'send_email', 'list_threads', 'list_thread_messages',
    'trust_sender', 'remove_trusted_sender', 'list_trusted_senders', 'is_trusted_sender',
    'update_account', 'get_email_signature', 'set_email_signature', 'migrate_email_signature_if_absent', 'open_external_url'}
names = set()
for path in (root / 'src').rglob('*.ts*'):
    if 'platform' in path.parts or 'poc' in path.parts:
        continue
    names.update(re.findall(r'\binvoke(?:<[^;]*?>)?\(\s*["\']([^"\']+)', path.read_text()))
arrays = set('list_kanban_cards get_message_labels list_labels list_contacts search_contacts search_contact_suggestions list_email_templates list_rules list_snoozed list_trusted_senders list_threads take_pending_mailto_urls'.split())
nulls = set('get_contact_by_email ai_get_config get_translate_config load_auto_backup_config get_global_proxy get_account_proxy get_oauth_account_proxy get_xoauth2_status'.split())
objects = set('get_message_labels_batch list_kanban_context_notes'.split())
noops = set('set_notifications_enabled set_tray_menu_labels sync_titlebar_theme clear_notification_attention'.split())
strings = set('get_email_signature migrate_email_signature_if_absent'.split())
special = {
    'get_autostart_enabled': 'false',
    'is_trusted_sender': 'false',
    'get_notification_status': '{ enabled: false, attention_active: false, platform: "unknown", app_id: null }',
    'get_account_proxy_setting': '{ mode: "inherit", proxy: null }',
    'get_oauth_account_proxy_setting': '{ mode: "inherit", proxy: null }',
}

def milestone(name):
    if name == 'advanced_search':
        return 'M3'
    if any(w in name for w in ('proxy', 'imap', 'pop3', 'xoauth2', 'test_account', 'add_account')):
        return 'M2'
    if any(w in name for w in ('webdav', 'backup', 'translate', 'ai_')):
        return 'M5'
    if any(w in name for w in ('notification', 'autostart', 'tray', 'titlebar', 'mailto', 'external', 'default_mail', 'app_log')):
        return 'M4'
    if any(w in name for w in ('contact', 'kanban', 'snooze', 'rule', 'template', 'signature', 'background', 'message_label', 'trusted', 'labels', 'reorder', 'update_account')):
        return 'M3'
    return 'M1'

source = ['// Generated by scripts/generate_commands.py. Review status changes before refreshing.',
          'import { implementedCommands, pending, startup } from "./commands";',
          'export const commands = {', '  ...implementedCommands,']
rows = []
for name in sorted(names):
    target = milestone(name)
    status = 'implemented' if name in implemented else 'not-implemented'
    if name in implemented:
        target = 'M2' if name in m2_commands else 'M1' if name in m1_commands else 'M0'
    else:
        value = None
        if name in arrays: value = '[]'
        elif name in nulls or name in noops: value = 'null'
        elif name in objects: value = '{}'
        elif name in strings: value = '\'\''
        elif name in special: value = special[name]
        if value is None:
            if name == 'set_xoauth2_refresh':
                source.append('  set_xoauth2_refresh: pending("set_xoauth2_refresh", "M2", "Raw refresh-token import is unsupported. Use Microsoft sign-in in account settings to verify the mailbox and authorize IMAP and SMTP separately."),')
            else:
                source.append(f'  {name}: pending("{name}", "{target}"),')
        else:
            status = 'startup-stub'
            source.append(f'  {name}: startup({value}, "{target}"),')
    rows.append(f'| `{name}` | {status} | {target} |')
source.extend(['} as const;', 'export type CommandName = keyof typeof commands;', ''])
(root / 'src/lib/platform/manifest.ts').write_text('\n'.join(source))
if args.manifest_only:
    print(f'{len(names)} commands, {len(implemented)} implemented; manifest refreshed (parity unchanged)')
    raise SystemExit(0)
(root / 'docs').mkdir(exist_ok=True)
(root / 'docs/parity.md').write_text('# Frontend command parity\n\n'
    f'{len(names)} invoke commands are currently present in the copied UI. The planning estimate was 141. '
    'This table and the manifest are refreshed together with `python3 scripts/generate_commands.py`. '
    'A test checks the command set against frontend source.\n\n'
    'Implemented entries call generated MyGO bindings. Startup stubs return explicit safe empty values '
    'for optional UI startup reads/preferences; they do not claim those features are implemented. '
    'Action stubs throw `NotImplemented` including the command name. Unknown commands always throw.\n\n'
    'Sync commands use the M1 account scheduler. Profile-local realtime preferences are applied '
    'before automatic requests start; manual mode permits only explicit manual triggers. '
    'Full scans and History pagination resume from committed checkpoints. '
    'Mail mutations and remote-write settings commands use the durable pending-op queue. '
    'Account access/reconnection uses generated AccountService methods and mail:account-changed directly; '
    'confirmed access failures pause the account without resending unknown sends. '
    'Gmail account edits save local preferences and encrypted signatures atomically. '
    'M2 protocol account add/test commands call typed AccountService methods; '
    'safe protocol configuration, revision-checked edits, selected folders, explicit endpoint CA trust, '
    'global/per-account HTTP CONNECT or SOCKS5 routes, Microsoft public-client consent/status/cancel '
    'and provider folder management use generated bindings directly. '
    'Their legacy invoke names remain pending unless an actual adapter exists. '
    'Microsoft Graph remains experimental; account capabilities gate actions, including POP3 limitations. '
    'No fixture result establishes real consent, keyring behavior or recipient delivery.\n\n'
    '| Command | Status | Milestone |\n|---|---|---|\n' + '\n'.join(rows) + '\n')
print(f'{len(names)} commands, {len(implemented)} implemented; parity and manifest refreshed')
